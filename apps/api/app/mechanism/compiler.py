"""Deterministic, versioned ``Candidate -> MJCF`` compiler.

Conventions mirror the reference solver (``app.mechanism.kinematics``):
ground pivots ``O2 = (0, 0)`` and ``O4 = (ground_length, 0)``, input angle
counter-clockwise from +x, output point is the rocker pin ``B``, parameters in
millimetres. The MuJoCo model is built in metres and the reference
configuration (all joint coordinates zero) is the assembled pose at
``input_motion.start_angle_deg``, so the ``connect`` loop-closure constraint
attaches exactly at the rocker tip for every configuration.

The emitted document is a pure function of the candidate parameters and the
start angle; the same compiler version always produces the same model
structure. Model-generated MJCF is never accepted: only typed candidates
compiled by this module reach the simulator.
"""

import math
from dataclasses import dataclass

from app.mechanism.kinematics import solve_rocker_pin
from app.mechanism.schemas import Candidate

COMPILER_VERSION = "0.1.0"

MM_TO_M = 0.001
GEOM_RADIUS_M = 0.004
GEOM_DENSITY = 1000.0
JOINT_ARMATURE = 1e-4
JOINT_DAMPING = 0.01
EQUALITY_SOLREF = (0.0021, 0.95)
EQUALITY_SOLIMP = "1 1 0.001"
DEFAULT_TIMESTEP_S = 1e-3
SOLVER_NAME = "Newton"
SOLVER_ITERATIONS = 100
SOLVER_TOLERANCE = 1e-12

_XML_TEMPLATE = """<mujoco model="mechanism_ai_four_bar">
  <!-- generated by the mechanism-ai mjcf compiler {compiler_version} -->
  <compiler angle="radian" inertiafromgeom="true"/>
  <option gravity="0 0 0" integrator="implicitfast" timestep="{timestep}"
          solver="{solver}" iterations="{iterations}" tolerance="{tolerance}">
    <flag contact="disable"/>
  </option>
  <default>
    <joint damping="{damping}" armature="{armature}"/>
    <geom type="capsule" size="{geom_radius}" density="{geom_density}" contype="0" conaffinity="0"/>
  </default>
  <worldbody>
    <site name="ground_pivot_a" pos="0 0 0" size="0.002"/>
    <site name="ground_pivot_b" pos="{ground_m} 0 0" size="0.002"/>
    <body name="crank" pos="0 0 0" quat="{crank_quat}">
      <joint name="crank_hinge" type="hinge" axis="0 0 1" damping="0" armature="{armature}"/>
      <geom name="crank_link" fromto="0 0 0 {crank_m} 0 0"/>
      <site name="crank_pin" pos="{crank_m} 0 0" size="0.002"/>
      <body name="coupler" pos="{crank_m} 0 0" quat="{coupler_quat}">
        <joint name="coupler_hinge" type="hinge" axis="0 0 1"/>
        <geom name="coupler_link" fromto="0 0 0 {coupler_m} 0 0"/>
        <site name="coupler_end" pos="{coupler_m} 0 0" size="0.002"/>
      </body>
    </body>
    <body name="rocker" pos="{ground_m} 0 0" quat="{rocker_quat}">
      <joint name="rocker_hinge" type="hinge" axis="0 0 1"/>
      <geom name="rocker_link" fromto="0 0 0 {rocker_m} 0 0"/>
      <site name="rocker_tip" pos="{rocker_m} 0 0" size="0.002"/>
    </body>
  </worldbody>
  <equality>
    <connect name="loop_closure" body1="coupler" body2="rocker" anchor="{coupler_m} 0 0"
             solref="{solref}" solimp="{solimp}"/>
  </equality>
</mujoco>
"""


class InvalidCandidateError(ValueError):
    """Raised when a candidate cannot be compiled into a valid MJCF model."""


@dataclass(frozen=True)
class CompiledModel:
    mjcf_xml: str
    compiler_version: str


def _fmt(value: float) -> str:
    return f"{value:.12g}"


def _quat_z(angle_rad: float) -> str:
    return f"{_fmt(math.cos(angle_rad / 2.0))} 0 0 {_fmt(math.sin(angle_rad / 2.0))}"


def _checked(value: float, name: str, *, positive: bool = False) -> float:
    if not math.isfinite(value):
        raise InvalidCandidateError(f"{name} must be finite")
    if positive and value <= 0.0:
        raise InvalidCandidateError(f"{name} must be positive")
    return value


def compile_candidate(candidate: Candidate) -> CompiledModel:
    """Compile validated parameters into a deterministic MuJoCo MJCF document."""
    parameters = candidate.parameters
    ground = _checked(parameters.ground_length, "ground_length", positive=True)
    crank = _checked(parameters.crank_length, "crank_length", positive=True)
    coupler = _checked(parameters.coupler_length, "coupler_length", positive=True)
    rocker = _checked(parameters.rocker_length, "rocker_length", positive=True)
    start_angle_deg = _checked(
        candidate.input_motion.start_angle_deg, "start_angle_deg"
    )
    _checked(candidate.input_motion.end_angle_deg, "end_angle_deg")

    start_angle_rad = math.radians(start_angle_deg)
    crank_pin = (crank * math.cos(start_angle_rad), crank * math.sin(start_angle_rad))
    intersections = solve_rocker_pin(
        crank_pin, (ground, 0.0), coupler, rocker
    )
    if intersections is None:
        raise InvalidCandidateError(
            f"the linkage cannot close at the start angle {start_angle_deg:.2f} degrees"
        )
    first, second = intersections
    rocker_pin = first if first[1] >= second[1] else second

    rocker_angle = math.atan2(rocker_pin[1], rocker_pin[0] - ground)
    coupler_angle = math.atan2(
        rocker_pin[1] - crank_pin[1], rocker_pin[0] - crank_pin[0]
    )

    mjcf_xml = _XML_TEMPLATE.format(
        compiler_version=COMPILER_VERSION,
        timestep=_fmt(DEFAULT_TIMESTEP_S),
        solver=SOLVER_NAME,
        iterations=SOLVER_ITERATIONS,
        tolerance=_fmt(SOLVER_TOLERANCE),
        damping=_fmt(JOINT_DAMPING),
        armature=_fmt(JOINT_ARMATURE),
        geom_radius=_fmt(GEOM_RADIUS_M),
        geom_density=_fmt(GEOM_DENSITY),
        ground_m=_fmt(ground * MM_TO_M),
        crank_m=_fmt(crank * MM_TO_M),
        coupler_m=_fmt(coupler * MM_TO_M),
        rocker_m=_fmt(rocker * MM_TO_M),
        crank_quat=_quat_z(start_angle_rad),
        coupler_quat=_quat_z(coupler_angle - start_angle_rad),
        rocker_quat=_quat_z(rocker_angle),
        solref=f"{_fmt(EQUALITY_SOLREF[0])} {_fmt(EQUALITY_SOLREF[1])}",
        solimp=EQUALITY_SOLIMP,
    )
    return CompiledModel(mjcf_xml=mjcf_xml, compiler_version=COMPILER_VERSION)
